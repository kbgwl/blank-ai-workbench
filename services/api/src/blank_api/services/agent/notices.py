"""系统事件的措辞：它是通知，不是人说的话，更不是批准。

后台命令跑完、monitor 吐了几行、子代理交了结论、工作流结束——这些都会在模型
下一次调用前插一条消息。四处的措辞原本各写一遍"这是系统事件，不是用户发言"，
但漏掉了更要紧的半句：**它也不构成批准**。

漏掉这半句的后果是具体的。模型问过一句"要我现在执行吗"，用户没回；
这期间后台命令恰好结束，系统插入一条通知。模型此刻读到的上一段"新输入"是
系统事件，如果它按"有人说话了=有人同意了"来处理，那一步就绕过了审批——
而审批的整条链路（拦截、留痕、用户点确认）全都在等那个从没发生的点击。

所以这段话必须是**一个常量**，四处引用同一份：措辞一旦分叉，就一定会有一处
忘了写后半句，而那一处就是漏洞。它同时明确了两件容易混淆的事：

1. 用户此前说过的话也不算批准（否则"待会儿你看着办"会被读成一张空白支票）；
2. 正在等批准就继续等（否则模型会拿"我已经解释过了"当作继续的理由）。
"""

